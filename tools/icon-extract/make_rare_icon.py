    rgba[..., 0], rgba[..., 1], rgba[..., 2] = INK
    rgba[..., 3] = np.asarray(alpha)
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(rgba, "RGBA").save(TARGET)
    print(f"wrote {{TARGET.relative_to(ROOT)}} ({{SIZE}}x{{SIZE}}, ink {{INK}})")
