def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    if not SOURCE_SVG.exists():
        print(f"missing {SOURCE_SVG}", file=sys.stderr)
        return 1
    text = SOURCE_SVG.read_text(encoding="utf-8")
    vb = text.split('viewBox="', 1)[1].split('"', 1)[0]
    d = text.split('d="', 1)[1].rsplit('"', 1)[0]

    icon = render(d, vb)
    cov = (np.asarray(icon)[..., 3] > 10).mean()
    print(f"glossary glyph {vb} -> {icon.size} RGBA, coverage {cov:.3f}, ink {INK}")

    if args.dry_run:
        print("dry-run: nothing written")
        return 0

    if TARGET.exists() and not BACKUP.exists():
        BACKUP.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(TARGET, BACKUP)
        print(f"backed up original -> {BACKUP.relative_to(ROOT)}")
    icon.save(TARGET)
    print(f"wrote {TARGET.relative_to(ROOT)}")

    # keep the surrounding path data out of the template's own braces
    path_lines = "\n".join(f'    "{chunk}"' for chunk in
                           [d[i:i + 96] for i in range(0, len(d), 96)])
    TOOL.write_text(TOOL_TEMPLATE.format(vb=vb, path_lines=path_lines, size=SIZE,
                                         pad=PAD, ss=SS, ink=INK), encoding="utf-8")
    print(f"wrote {TOOL.relative_to(ROOT)} (self-contained generator)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
